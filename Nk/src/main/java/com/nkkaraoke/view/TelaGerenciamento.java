    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
    Long id = Long.parseLong(txtId.getText());
    java.util.Optional<com.nkkaraoke.model.Reserva> reserva = com.mycompany.nk.Nk.repo.findById(id);
    
    if (reserva.isPresent()) {
        com.nkkaraoke.model.Reserva r = reserva.get();
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Reserva Encontrada!\nCliente: " + r.getNomeCliente() + 
            "\nMesa: " + r.getNumeroMesa() + 
            "\nPessoas: " + r.getQuantidadePessoas());
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Nenhuma reserva encontrada com o ID: " + id);
    }
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Por favor, insira um ID válido!");
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {
    Long id = Long.parseLong(txtId.getText());
    java.util.Optional<com.nkkaraoke.model.Reserva> reservaOptional = com.mycompany.nk.Nk.repo.findById(id);
    
    if (reservaOptional.isPresent()) {
        com.nkkaraoke.model.Reserva r = reservaOptional.get();
        String novasPessoas = javax.swing.JOptionPane.showInputDialog(this, "Quantidade atual: " + r.getQuantidadePessoas() + "\nDigite a nova quantidade de pessoas:");
        
        if (novasPessoas != null && !novasPessoas.trim().isEmpty()) {
            r.setQuantidadePessoas(Integer.parseInt(novasPessoas));
            com.mycompany.nk.Nk.repo.save(r);
            javax.swing.JOptionPane.showMessageDialog(this, "Reserva atualizada com sucesso!");
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Reserva não encontrada!");
    }
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Erro ao atualizar. Verifique os valores.");
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        try {
    Long id = Long.parseLong(txtId.getText());
    java.util.Optional<com.nkkaraoke.model.Reserva> reserva = com.mycompany.nk.Nk.repo.findById(id);
    
    if (reserva.isPresent()) {
        com.mycompany.nk.Nk.repo.deleteById(id);
        javax.swing.JOptionPane.showMessageDialog(this, "Reserva excluída com sucesso!");
        txtId.setText("");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Reserva não encontrada!");
    }
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Erro ao excluir. Insira um ID válido.");
}
    }//GEN-LAST:event_jButton3ActionPerformed

